# 第8回：訓練平均を固定して評価する。work全体を開いて実行します。
library(readr)
library(dplyr)

records <- read_csv("exercises/lesson08/data/equipment.csv", show_col_types = FALSE)
print(dim(records))
print(sapply(records, class))
print(colSums(is.na(records)))
train <- filter(records, split == "train")
validation <- filter(records, split == "validation")
baseline <- mean(train$energy_kwh)
print(train$id)
print(validation$id)
cat("訓練件数", nrow(train), "\n")
cat("検証件数", nrow(validation), "\n")
cat("訓練平均 kWh", baseline, "\n")
train_error <- abs(train$energy_kwh - baseline)
train_mae <- mean(train_error)
validation_error <- abs(validation$energy_kwh - baseline)
validation_mae <- mean(validation_error)
cat("訓練MAE kWh", train_mae, "\n")
cat("検証MAE kWh", validation_mae, "\n")
